// Pure string transform, safe to import from client components. The
// server-only uniqueness check lives in lib/blog/slugify.ts, which reuses
// this function.
export function slugify(title: string): string {
  return title
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9\s-]/g, "")
    .replace(/\s+/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80);
}
